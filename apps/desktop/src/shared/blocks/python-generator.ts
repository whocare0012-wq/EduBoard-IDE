import * as Blockly from 'blockly/core';
import { Order, PythonGenerator, pythonGenerator } from 'blockly/python';
import type { GeneratedCode } from './arduino-generator';

class MicroPythonGenerator extends PythonGenerator {
  readonly devices = new Map<string, string>();
  constructor(workspace: Blockly.Workspace) {
    super('MicroPython');
    Object.assign(this.forBlock, pythonGenerator.forBlock);
    this.addReservedWords('Pin,ADC,time,dht,neopixel');
    for (let pin = 0; pin <= 48; pin++) this.addReservedWords(['eduPin_', 'eduAdc_', 'eduDht_', 'eduDhtTime_', 'eduReadDht_', 'eduStrip_'].map(prefix => prefix + pin).join(','));
    this.init(workspace);
    this.definitions_.imports = 'from machine import Pin, ADC\nimport time';
    this.definitions_.variables = workspace.getVariableMap().getAllVariables().map(variable => this.nameDB_!.getName(variable.getId(), Blockly.Names.NameType.VARIABLE) + ' = 0').join('\n');
    const number = (block: Blockly.Block, field: string, min = 0, max = 48): number => {
      const n = Number(block.getFieldValue(field));
      if (!Number.isInteger(n) || n < min || n > max) throw new Error('积木数字超出范围：' + field);
      return n;
    };
    const pin = (block: Blockly.Block): string => {
      const n = number(block, 'PIN'); const name = 'eduPin_' + n;
      this.definitions_[name] = name + ' = Pin(' + n + ')';
      return name;
    };
    this.forBlock.edu_pin_mode = block => {
      const mode = block.getFieldValue('MODE');
      return pin(block) + '.init(' + (mode === 'OUTPUT' ? 'Pin.OUT' : mode === 'INPUT_PULLUP' ? 'Pin.IN, Pin.PULL_UP' : 'Pin.IN') + ')\n';
    };
    this.forBlock.edu_write = block => pin(block) + '.value(' + (block.getFieldValue('VALUE') === 'HIGH' ? '1' : '0') + ')\n';
    this.forBlock.edu_read = block => [pin(block) + '.value()', Order.FUNCTION_CALL];
    this.forBlock.edu_analog_read = block => {
      const n = number(block, 'PIN'); const name = 'eduAdc_' + n;
      this.definitions_[name] = name + ' = ADC(Pin(' + n + '))';
      return [name + '.read_u16()', Order.FUNCTION_CALL];
    };
    this.forBlock.edu_delay = block => 'time.sleep_ms(' + number(block, 'MS', 0, 86_400_000) + ')\n';
    this.forBlock.edu_print = block => 'print(' + (this.valueToCode(block, 'VALUE', Order.NONE) || '""') + ')\n';
    this.forBlock.edu_dht_read = block => {
      const n = number(block, 'PIN'); const sensor = 'eduDht_' + n; const stamp = 'eduDhtTime_' + n; const read = 'eduReadDht_' + n;
      this.definitions_.import_dht = 'import dht';
      this.definitions_[sensor] = sensor + ' = dht.DHT11(Pin(' + n + '))\n' + stamp + ' = None';
      this.definitions_[read] = 'def ' + read + '(humidity):\n    global ' + stamp + '\n    now = time.ticks_ms()\n    if ' + stamp + ' is None or time.ticks_diff(now, ' + stamp + ') >= 2000:\n        try:\n            ' + sensor + '.measure()\n            ' + stamp + ' = now\n        except OSError:\n            return float("nan")\n    return ' + sensor + '.humidity() if humidity else ' + sensor + '.temperature()';
      return [read + '(' + (block.getFieldValue('KIND') === 'HUM' ? 'True' : 'False') + ')', Order.FUNCTION_CALL];
    };
    this.forBlock.edu_oled_text = () => { throw new Error('SH1106 积木当前仅支持 Arduino；MicroPython 需要另装对应显示驱动。'); };
    this.forBlock.edu_pixel = block => {
      const n = number(block, 'PIN'); const count = number(block, 'COUNT', 1, 256); const index = number(block, 'INDEX', 0, 255);
      if (index >= count) throw new Error('NeoPixel 灯珠序号必须小于灯数（从 0 开始）。');
      const name = 'eduStrip_' + n;
      if (this.devices.has(name) && this.devices.get(name) !== String(count)) throw new Error('同一灯带的灯数不一致。');
      this.devices.set(name, String(count)); this.definitions_.import_neopixel = 'import neopixel';
      this.definitions_[name] = name + ' = neopixel.NeoPixel(Pin(' + n + '), ' + count + ')';
      return name + '[' + index + '] = (' + number(block, 'R', 0, 255) + ', ' + number(block, 'G', 0, 255) + ', ' + number(block, 'B', 0, 255) + ')\n' + name + '.write()\n';
    };
  }
}

export function generateMicroPython(workspace: Blockly.Workspace): GeneratedCode {
  const gen = new MicroPythonGenerator(workspace);
  const roots = workspace.getTopBlocks(true).filter(block => block.isEnabled());
  const setup = roots.filter(block => block.type === 'edu_setup'); const loop = roots.filter(block => block.type === 'edu_loop');
  if (setup.length > 1 || loop.length > 1) throw new Error('只能有一个“启动时”和一个“不断重复”积木。');
  const startup = setup[0] ? gen.statementToCode(setup[0], 'BODY').split('\n').map(line => line.startsWith(gen.INDENT) ? line.slice(gen.INDENT.length) : line).join('\n') : '';
  const repeating = loop[0] ? gen.statementToCode(loop[0], 'BODY') : '';
  const orphaned = roots.filter(block => block.type !== 'edu_setup' && block.type !== 'edu_loop').length;
  const code = '# Generated by EduBoard IDE. Runs on the MicroPython device.\n' + gen.finish(startup + '\nwhile True:\n' + (repeating || gen.INDENT + 'pass\n'));
  return { code, warnings: orphaned ? ['有 ' + orphaned + ' 个未连接积木不会执行。'] : [], libraries: [] };
}
