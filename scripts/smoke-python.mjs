// UI/file/parser checks only. No real serial port is ever opened by this check.
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, lstat, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { _electron as electron } from 'playwright';
import { closeSmoke } from './close-smoke.mjs';

const require = createRequire(import.meta.url);
const root = await mkdtemp(join(tmpdir(), 'eduboard-python-ui-'));
const environment = Object.fromEntries(Object.entries(process.env).filter(([key, value]) => value !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(key)));
const application = await electron.launch({ executablePath: process.env.EDUBOARD_SMOKE_EXE || require('electron'), args: process.env.EDUBOARD_SMOKE_EXE ? [] : ['.'], cwd: process.cwd(), env: { ...environment, EDUBOARD_USER_DATA: join(root, 'profile'), EDUBOARD_PYTHON_PATH: process.env.EDUBOARD_PYTHON_PATH || 'python', ARDUINO_CLI_PATH: join(root, 'missing-cli.exe') } });
try {
  const page = await application.firstWindow(); const errors = [];
  await page.setViewportSize({ width: 1280, height: 820 });
  page.on('pageerror', error => errors.push(error.message));
  await page.context().setOffline(true);
  await page.locator('.monaco-editor').waitFor();
  await application.evaluate(({ dialog }, path) => {
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: path });
    dialog.showMessageBoxSync = () => 1;
    dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false });
  }, join(root, 'PythonLesson.eduboard.json'));
  await page.getByRole('button', { name: 'Python', exact: true }).click();
  await page.getByRole('button', { name: '检查语法', exact: true }).waitFor();
  await page.getByRole('status').filter({ hasText: '准备就绪' }).waitFor();
  const editor = page.locator('.monaco-editor textarea').first();
  const sentinel = join(root, 'must-not-execute.txt');
  const source = 'import pathlib\npathlib.Path(' + JSON.stringify(sentinel) + ').write_text("executed")\n';
  await editor.focus(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.insertText(source);
  await page.getByText('有未保存更改', { exact: true }).waitFor();
  await page.getByRole('button', { name: '检查语法', exact: true }).click();
  await page.locator('.console').filter({ hasText: '[语法检查] 成功' }).waitFor();
  await assert.rejects(lstat(sentinel), { code: 'ENOENT' });
  const saved = JSON.parse(await readFile(join(root, 'PythonLesson', 'PythonLesson.eduboard.json'), 'utf8'));
  assert.equal(saved.language, 'micropython'); assert.equal(await readFile(join(root, 'PythonLesson', 'main.py'), 'utf8'), source);
  await editor.focus(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.insertText('def broken(:\n');
  await page.getByRole('button', { name: '检查语法', exact: true }).click();
  await page.locator('.console').filter({ hasText: '[语法检查] 失败' }).waitFor();
  await page.getByRole('combobox', { name: '固件 / 板型' }).selectOption('esp32c3');
  await page.getByRole('button', { name: '新建图形化示例', exact: true }).click();
  if (await page.getByRole('dialog').isVisible()) await page.getByRole('button', { name: '放弃更改并继续', exact: true }).click();
  await page.locator('.code-pane .view-lines').filter({ hasText: 'Generated by EduBoard IDE' }).waitFor();
  await application.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }); }, join(root, 'PyBlocks.eduboard.json'));
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('已保存', { exact: true }).waitFor();
  const blocks = JSON.parse(await readFile(join(root, 'PyBlocks', 'PyBlocks.eduboard.json'), 'utf8'));
  assert.equal(blocks.mode, 'blocks'); assert.equal(blocks.microBoard, 'esp32c3'); assert.match(blocks.source, /eduPin_3/);
  await page.getByRole('button', { name: '运行到设备', exact: true }).click();
  await page.locator('.console').filter({ hasText: '请先选择实际开发板的串口' }).waitFor();
  await page.getByRole('button', { name: '设备', exact: true }).click();
  await page.getByText('固件安装（会清空设备）', { exact: true }).click();
  const invalid = join(root, 'invalid.bin'); await writeFile(invalid, Buffer.alloc(64));
  await application.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, invalid);
  await page.getByRole('button', { name: '选择并校验固件', exact: true }).click();
  await page.locator('.console').filter({ hasText: '固件格式' }).waitFor();
  assert.equal(await page.getByRole('button', { name: '擦除并刷入固件', exact: true }).isDisabled(), true);
  if (process.env.EDUBOARD_FIRMWARE_DIR) {
    const firmware = join(process.env.EDUBOARD_FIRMWARE_DIR, 'ESP32_GENERIC_C3-20260824-v1.29.0.bin');
    await application.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, firmware);
    await page.getByRole('button', { name: '选择并校验固件', exact: true }).click();
    await page.getByText(/已校验 ESP32_GENERIC_C3/).waitFor();
    await page.getByLabel('串口', { exact: true }).fill('COM9999');
    await page.getByRole('button', { name: '擦除并刷入固件', exact: true }).click();
    await page.locator('.console').filter({ hasText: '已取消刷机' }).waitFor();
  }
  await mkdir(resolve('output/playwright'), { recursive: true });
  await page.screenshot({ path: resolve('output/playwright/micropython.png') });
  assert.deepEqual(errors, []);
  console.log('PASS MicroPython desktop: Python project save, parser without host execution, syntax failure, block generator/C3 defaults, missing-port guard, invalid firmware and canceled flash. No hardware writes.');
} finally { await closeSmoke(application); await rm(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }); }
