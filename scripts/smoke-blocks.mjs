import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { _electron as electron } from 'playwright';
import { closeSmoke } from './close-smoke.mjs';

const require = createRequire(import.meta.url);
const temp = await mkdtemp(join(tmpdir(), 'eduboard-blocks-'));
const environment = Object.fromEntries(Object.entries(process.env).filter(([key, value]) => value !== undefined && !['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL'].includes(key)));
const application = await electron.launch({ executablePath: process.env.EDUBOARD_SMOKE_EXE || require('electron'), args: process.env.EDUBOARD_SMOKE_EXE ? [] : ['.'], cwd: process.cwd(), env: { ...environment, EDUBOARD_USER_DATA: join(temp, 'profile'), ARDUINO_CLI_PATH: join(temp, 'missing-cli.exe') } });
try {
  const page = await application.firstWindow();
  await page.setViewportSize({ width: 1280, height: 820 });
  const errors = []; const remote = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) remote.push(request.url()); });
  await page.context().setOffline(true);
  await page.locator('.monaco-editor').waitFor();
  await application.evaluate(({ dialog }) => {
    dialog.showMessageBoxSync = () => 1;
    dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false });
  });
  await page.getByRole('button', { name: '新建图形化示例', exact: true }).click();
  await page.locator('.blocklySvg').waitFor();
  await page.locator('.code-pane .view-lines').filter({ hasText: 'Generated by EduBoard IDE' }).waitFor();
  await page.getByRole('button', { name: '采用生成代码', exact: true }).waitFor();
  const selected = join(temp, 'LedLesson.eduboard.json');
  const savedPath = join(temp, 'LedLesson', 'LedLesson.eduboard.json');
  await application.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }); }, selected);
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('已保存', { exact: true }).waitFor();
  const first = JSON.parse(await readFile(savedPath, 'utf8'));
  assert.equal(first.mode, 'blocks');
  assert.match(first.source, /digitalWrite\(2, HIGH\)/);
  await page.locator('.blocklyText').filter({ hasText: /^1000$/ }).first().click();
  const field = page.locator('.blocklyHtmlInput');
  await field.fill('250');
  await field.press('Enter');
  await page.getByText('有未保存更改', { exact: true }).waitFor();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('已保存', { exact: true }).waitFor();
  const edited = JSON.parse(await readFile(savedPath, 'utf8'));
  assert.match(edited.source, /delay\(250\)/);
  assert.equal(await readFile(join(temp, 'LedLesson', 'LedLesson.ino'), 'utf8'), edited.source);
  await writeFile(join(temp, 'LedLesson', 'LedLesson.ino'), '// inconsistent external edit');
  const stale = await page.evaluate(() => window.eduboard.compile('esp32:esp32:esp32'));
  assert.equal(stale.ok, false); assert.match(stale.stderr, /不一致/);
  await writeFile(join(temp, 'LedLesson', 'LedLesson.ino'), edited.source);
  await mkdir(resolve('output/playwright'), { recursive: true });
  await page.screenshot({ path: resolve('output/playwright/blockly.png') });
  await application.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, savedPath);
  await page.getByRole('button', { name: '打开', exact: true }).click();
  await page.locator('.blocklyText').filter({ hasText: /^250$/ }).first().waitFor();
  await page.getByRole('button', { name: '采用生成代码', exact: true }).click();
  await page.locator('.section-head').getByText('Arduino C++', { exact: true }).waitFor();
  assert.equal(await page.locator('.blocklySvg').count(), 0);
  const editor = page.locator('.monaco-editor textarea').first();
  await editor.focus(); await page.keyboard.press('ControlOrMeta+End'); await page.keyboard.insertText('// editable text copy');
  await page.getByText('有未保存更改', { exact: true }).waitFor();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('已保存', { exact: true }).waitFor();
  const textProject = JSON.parse(await readFile(savedPath, 'utf8'));
  assert.equal(textProject.mode, 'text'); assert.match(textProject.drafts.arduino, /editable text copy/);
  assert.deepEqual(textProject.workspace, edited.workspace, 'Text editing preserves blocks in the same project');
  await page.getByRole('button', { name: '新建图形化示例', exact: true }).click();
  await page.locator('.blocklySvg').waitFor();
  await application.evaluate(({ dialog }, path) => {
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: path });
    dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false });
  }, savedPath);
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '准备就绪' }).waitFor();
  assert.equal(JSON.parse(await readFile(savedPath, 'utf8')).source, textProject.source, 'Canceled overwrite must preserve the existing project');
  await mkdir(resolve('output/playwright'), { recursive: true });
  assert.deepEqual(errors, []); assert.deepEqual(remote, []);
  console.log('PASS Blockly desktop: local media, visible generation, field editing, JSON save/reopen, retained blocks during text editing and canceled overwrite.');
} catch (error) {
  await mkdir(resolve('output/playwright'), { recursive: true });
  const page = await application.firstWindow();
  await page.screenshot({ path: resolve('output/playwright/blockly-failure.png') }).catch(() => {});
  throw error;
} finally { await closeSmoke(application); await rm(temp, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }); }
